    cols = st.columns(2)
    for i, (name, scope, limits) in enumerate(scopes):
        with cols[i % 2].container(border=True):
            st.markdown(f"**{name}**" + (f" · model: `{limits.get('model')}`" if limits.get("model") else ""))
            for row in policy.status(scope, limits):
                spent = fmt_usd(row["spent"]) if row["key"].endswith("usd") else fmt_tokens(row["spent"])
                if row["limit"] is None:
                    st.caption(f"{label[row['key']]}: {spent} · no limit".replace("$", r"\$"))
                    continue
                lim = fmt_usd(row["limit"]) if row["key"].endswith("usd") else fmt_tokens(row["limit"])
                state = ("⛔ over limit" if row["pct"] >= 100 else "⚠️ near limit — calls downgrade to the cheapest model"
                         if row["pct"] >= soft else "✅ ok")
                meter = f"{label[row['key']]}: {spent} of {lim} ({row['pct']}%) · {state}"
                st.progress(min(row["pct"], 100) / 100, text=meter.replace("$", r"\$"))  # "$" would start LaTeX

    st.subheader("Controls")
    with st.form("budget_form"):
        g = settings["global"]
        a, b, c = st.columns(3)
        cheapest = a.toggle("Cheapest model only (emergency switch)", value=g["cheapest_only"],
                            help=f"Every call uses {pricing.CHEAPEST_MODEL}.")
        soft_v = b.number_input("Soft threshold % (downgrade + warning)", 1, 100, int(g["soft_pct"]))
        model_opts = [""] + sorted(pricing.PRICES)
        default_m = c.selectbox("Default model (empty = DEFAULT_MODEL env)", model_opts,
                                index=model_opts.index(g["default_model"] or ""))

        def limit_inputs(prefix, cfg):
            cs = st.columns(4)
            out = {}
            for col, key in zip(cs, LIMIT_KEYS):
                step = 0.01 if key.endswith("usd") else 1000.0
                v = col.number_input(f"{prefix} {label[key]} limit (0 = none)", min_value=0.0, step=step,
                                     value=float(cfg.get(key) or 0), key=f"{prefix}_{key}")
                out[key] = v if v > 0 else None
            return out

