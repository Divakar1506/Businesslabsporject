# --- streaming playground -------------------------------------------------
with tab_play:
    st.caption(f"Sends a logged call through the gateway in **{MODE}** mode and streams the reply.")
    p_task = st.selectbox("Bill to task", tasks, key="play_task")
    prompt = st.text_area("Prompt", "In two sentences, what does a knowledge base API do?")
    if st.button("Stream reply", type="primary"):
        gw = Gateway(store=store)
        try:
            handle = gw.stream(task=p_task, endpoint="playground", max_tokens=512,
                               messages=[{"role": "user", "content": prompt}])
            st.write_stream(handle)
            r = handle.result
            st.caption(f"{r.model} · {r.input_tokens} in / {r.output_tokens} out · {fmt_usd(r.cost_usd)} · "
                       f"{r.latency_ms:,.0f} ms total" + (f" · {r.note}" if r.note else ""))
        except BudgetExceeded as e:
            st.error(f"Blocked by budget: {e}")
        except Exception as e:
            hint = " Is Ollama running (`ollama serve`)?" if MODE == "ollama" else ""
            st.error(f"Call failed: {type(e).__name__}: {e}.{hint}")
