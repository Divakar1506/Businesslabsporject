def cache_savings(rows) -> float:
    """What cache reads saved versus paying the full input price."""
    return sum((r["cache_read_tokens"] or 0) * (pricing.PRICES[r["model"]]["input"] - pricing.PRICES[r["model"]]["cache_read"])
               for r in rows if r["model"] in pricing.PRICES) / 1_000_000


def month_projection(task) -> tuple[float, float]:
    """(spent this month, straight-line projection to month end)."""
    now = datetime.now()
    spent, _ = store.spend(task, month_start())
    elapsed_days = max((now.timestamp() - month_start()) / 86400, 1 / 24)
    return spent, spent / elapsed_days * calendar.monthrange(now.year, now.month)[1]


