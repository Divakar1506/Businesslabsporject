def since_for(label: str) -> float:
    today = datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)
    return (today - timedelta(days=RANGES[label] - 1 if RANGES[label] else 0)).timestamp()


def fmt_tokens(n: float) -> str:
    n = float(n or 0)
    for unit, div in (("B", 1e9), ("M", 1e6), ("K", 1e3)):
        if abs(n) >= div:
            return f"{n / div:.2f}{unit}"
    return f"{n:.0f}"


def fmt_usd(x: float) -> str:
    x = float(x or 0)
    return f"${x:,.4f}" if x < 1 else f"${x:,.2f}"


def bar_style(chart: alt.Chart) -> alt.Chart:
    return chart.configure_view(strokeWidth=0).configure_axis(grid=False, domainColor=OTHER, tickColor=OTHER)


